// Desenha a partir do canto superior esquerdo; cada caractere ocupa 6 colunas de `pitch`.
export function drawDotMatrix(ctx, text, x, y, pitch) {
  const r = pitch * 0.36;
  ctx.beginPath();
  [...text].forEach((ch, i) => {
    const glyph = GLYPHS[ch];
    if (!glyph) throw new Error(`Caractere sem glifo: ${ch}`);
    glyph.forEach((row, gy) => {
      [...row].forEach((bit, gx) => {
        if (bit !== '1') return;
        const cx = x + (i * 6 + gx) * pitch + pitch / 2;
        const cy = y + gy * pitch + pitch / 2;
        ctx.moveTo(cx + r, cy);
        ctx.arc(cx, cy, r, 0, Math.PI * 2);
      });
    });
  });
  ctx.fill();
}
